"""Install and check Studio's pre-commit hook (m0e-plan §3).

One runner per clone in the git common dir; a link from whatever git actually runs:
plain git -> a shim in the hooks dir (the previous hook chained first); husky -> a block in the tracked
.husky/pre-commit (proposed; written only with --husky-apply); lefthook -> a block in the untracked
lefthook-local.yml. Never writes .husky/_ or a hooks path outside the work tree (a global one)."""

import json
import os
import re
import stat

from .. import ignore
from ..commit import spaths
from . import templates as T

LEFTHOOK_CONFIGS = ("lefthook.yml", ".lefthook.yml", "lefthook.yaml", ".lefthook.yaml", "lefthook.toml",
                    ".lefthook.toml", "lefthook.json", ".lefthook.json")
OVERWRITERS = (("pre-commit", "File generated by pre-commit"), ("simple-git-hooks", "simple-git-hooks"),
               ("husky v4", "husky.sh"), ("lefthook", "lefthook"))


class Result(object):
    def __init__(self, manager):
        self.manager = manager
        self.wrote = []
        self.proposal = None
        self.warnings = []
        self.problems = []
        self.code = 0

    def as_dict(self):
        return {"manager": self.manager, "wrote": self.wrote, "proposal": self.proposal, "warnings": self.warnings,
                "problems": self.problems, "code": self.code}


def _read(p):
    try:
        with open(p, encoding="utf-8", errors="surrogateescape") as f:
            return f.read()
    except OSError:
        return None


def _write(p, text, mode=None):
    """Atomic; returns True when the content changed (same content: nothing is written)."""
    if _read(p) == text and (mode is None or (os.stat(p).st_mode & 0o777) == mode):
        return False
    os.makedirs(os.path.dirname(p), exist_ok=True)
    tmp = "%s.studio-tmp.%d" % (p, os.getpid())
    with open(tmp, "w", encoding="utf-8", errors="surrogateescape") as f:
        f.write(text)
    if mode is not None:
        os.chmod(tmp, mode)
    elif os.path.exists(p):
        os.chmod(tmp, stat.S_IMODE(os.stat(p).st_mode))
    os.replace(tmp, p)
    return True


def _inside(path, root):
    path, root = os.path.realpath(path), os.path.realpath(root)
    return path == root or path.startswith(root.rstrip("/") + "/")


def _package_json(top):
    try:
        with open(os.path.join(top, "package.json"), encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def detect(git, top):
    """{manager, hooks_dir, hooks_path (config), detail}."""
    hp = git.config("core.hooksPath")
    hooks_dir = git.git_path("hooks")
    pkg = _package_json(top)
    deps = {}
    for k in ("dependencies", "devDependencies"):
        if isinstance(pkg.get(k), dict):
            deps.update(pkg[k])
    info = {"hooks_dir": hooks_dir, "hooks_path": hp, "detail": None}
    if hp:
        norm = hp.rstrip("/")
        if norm.endswith(".husky/_") or norm == ".husky" or norm.endswith("/.husky"):
            return dict(info, manager="husky", installed=True)
        if _inside(hooks_dir, top):
            return dict(info, manager="custom-tracked")
        return dict(info, manager="global-path")
    if os.path.isdir(os.path.join(top, ".husky")) and ("husky" in deps or "husky" in pkg):
        return dict(info, manager="husky", installed=False)
    if any(os.path.exists(os.path.join(top, n)) for n in LEFTHOOK_CONFIGS):
        return dict(info, manager="lefthook")
    cur = _read(os.path.join(hooks_dir, "pre-commit")) or ""
    if T.MARK not in cur:
        for name, sign in OVERWRITERS:
            if sign in cur:
                return dict(info, manager="plain", detail=name)
    if "simple-git-hooks" in pkg or os.path.exists(os.path.join(top, ".pre-commit-config.yaml")):
        return dict(info, manager="plain", detail="simple-git-hooks" if "simple-git-hooks" in pkg else "pre-commit")
    return dict(info, manager="plain")


def runner_path(git):
    return os.path.join(git.common_dir(), T.RUNNER_REL)


def _ensure_exclude(git, root, extra):
    p = os.path.join(git.common_dir(), "info", "exclude")
    text = _read(p) or ""
    try:
        new = ignore.ensure(text, ignore.render(root, extra))
    except ignore.BlockError as e:
        raise _Fail("info/exclude: %s — fix it by hand" % e)
    return p if _write(p, new) else None


class _Fail(Exception):
    pass


def install(git, top, env, husky_apply=False):
    det = detect(git, top)
    res = Result(det["manager"])
    roots = spaths.studio_roots(top, git, env, git.head())
    try:
        if det["manager"] == "global-path":
            res.code = 1
            res.problems.append("core.hooksPath points outside this repository (%s) — Studio does not write there "
                                "(it would run in every repository). Add this line to that pre-commit hook by hand: "
                                "%s" % (det["hooks_path"], _husky_line()))
            return res
        if det["manager"] == "custom-tracked":
            res.code = 4
            res.proposal = T.husky_block()
            res.warnings.append("core.hooksPath is a folder in this repository (%s) — shared with the team; add the "
                                "proposed block to its pre-commit by hand (a person decides)" % det["hooks_path"])
        extra = ("/lefthook-local.yml",) if det["manager"] == "lefthook" else ()
        w = _ensure_exclude(git, roots[0], extra)
        if w:
            res.wrote.append(w)
        rp = runner_path(git)
        if _write(rp, T.runner(roots), 0o755):
            res.wrote.append(rp)
        if det["manager"] == "plain":
            _install_plain(det, res)
            if det.get("detail"):
                res.warnings.append("%s manages git hooks here and may overwrite Studio's hook when it reinstalls — "
                                    "\"hooks.py status\" tells when; then run \"hooks.py install\" again"
                                    % det["detail"])
        elif det["manager"] == "husky":
            p = os.path.join(top, ".husky", "pre-commit")
            if husky_apply:
                text = _read(p) or ""
                try:
                    new = T.put_block(text, T.husky_block())
                except ValueError as e:
                    raise _Fail(".husky/pre-commit: %s" % e)
                if _write(p, new, None if os.path.exists(p) else 0o755):
                    res.wrote.append(p)
            else:
                res.proposal = T.husky_block()
                res.code = 4
                res.warnings.append(".husky/pre-commit is shared with the team: Studio proposes this block; a person "
                                    "decides (then run \"hooks.py install --husky-apply\")")
            if not det.get("installed"):
                res.warnings.append("husky is not installed in this clone (npm install) — its hooks do not run yet")
        elif det["manager"] == "lefthook":
            p = os.path.join(top, "lefthook-local.yml")
            text = _read(p) or ""
            try:
                sp = T.find_block(text)
            except ValueError as e:
                raise _Fail("lefthook-local.yml: %s" % e)
            outside = text if sp is None else text[:sp[0]] + text[sp[1]:]
            if re.search(r"(?m)^pre-commit\s*:", outside):
                res.code = 1
                res.proposal = T.lefthook_block()
                res.problems.append("lefthook-local.yml already has a pre-commit section — Studio cannot merge YAML "
                                    "safely; add the proposed command under it by hand")
                return res
            if _write(p, T.put_block(text, T.lefthook_block())):
                res.wrote.append(p)
            hook = _read(os.path.join(det["hooks_dir"], "pre-commit")) or ""
            if "lefthook" not in hook:
                res.warnings.append("lefthook's git hook is not installed in this clone — run \"lefthook install\"")
    except _Fail as e:
        res.code = 1
        res.problems.append(str(e))
    return res


def _husky_line():
    return 'sh "$(git rev-parse --git-common-dir)/%s" || exit $?' % T.RUNNER_REL


def _install_plain(det, res):
    hd = det["hooks_dir"]
    p = os.path.join(hd, "pre-commit")
    chained = os.path.join(hd, T.CHAINED)
    cur = _read(p)
    if cur is not None and T.MARK not in cur:
        if os.path.exists(chained) and _read(chained) != cur:
            raise _Fail("both %s and %s exist and differ — a person tidies them first" % (p, chained))
        os.replace(p, chained)
        res.wrote.append(chained)
    try:
        if _write(p, T.shim(), 0o755):
            res.wrote.append(p)
    except BaseException:
        if cur is not None and T.MARK not in cur and os.path.exists(chained) and not os.path.exists(p):
            os.replace(chained, p)
        raise


def status(git, top, env):
    """{manager, valid, reasons, files}."""
    det = detect(git, top)
    roots = spaths.studio_roots(top, git, env, git.head())
    reasons, files = [], []
    rp = runner_path(git)
    files.append(rp)
    cur = _read(rp)
    if cur is None:
        reasons.append("the runner is missing (%s)" % rp)
    elif cur != T.runner(roots):
        reasons.append("the runner differs from this version's (edited, older, or studio_root changed) — "
                       "run hooks.py install")
    elif not os.access(rp, os.X_OK):
        reasons.append("the runner is not executable")
    ex = _read(os.path.join(git.common_dir(), "info", "exclude")) or ""
    if not ignore.ok(ex, roots[0]):
        reasons.append("info/exclude lacks Studio's block")
    m = det["manager"]
    if m in ("global-path", "custom-tracked"):
        reasons.append("core.hooksPath is %s — Studio's hook must be linked by hand" % det["hooks_path"])
    elif m == "plain":
        p = os.path.join(det["hooks_dir"], "pre-commit")
        files.append(p)
        h = _read(p)
        if h is None:
            reasons.append("no pre-commit hook")
        elif T.MARK not in h:
            reasons.append("the pre-commit hook was overwritten%s" % (" by " + det["detail"] if det.get("detail") else ""))
        elif h != T.shim():
            reasons.append("the pre-commit shim differs from this version's")
        elif not os.access(p, os.X_OK):
            reasons.append("the pre-commit shim is not executable")
    elif m == "husky":
        p = os.path.join(top, ".husky", "pre-commit")
        files.append(p)
        if not det.get("installed"):
            reasons.append("husky is not installed in this clone (npm install)")
        elif not os.path.exists(os.path.join(top, ".husky", "_", "pre-commit")) and \
                (det.get("hooks_path") or "").rstrip("/").endswith("_"):
            reasons.append("husky's generated hooks (.husky/_) are missing")
        text = _read(p) or ""
        if T.husky_block() not in text:
            reasons.append("the proposed Studio block is not in .husky/pre-commit")
        elif T.stops_before_block(text):
            reasons.append("the hook ends before the Studio block (an exit/return/exec line above it)")
    elif m == "lefthook":
        p = os.path.join(top, "lefthook-local.yml")
        files.append(p)
        if T.lefthook_block() not in (_read(p) or ""):
            reasons.append("lefthook-local.yml lacks Studio's block")
        if "lefthook" not in (_read(os.path.join(det["hooks_dir"], "pre-commit")) or ""):
            reasons.append("lefthook's git hook is not installed (lefthook install)")
    return {"manager": m, "valid": not reasons, "reasons": reasons, "files": files,
            "warnings": reincluded_local(top, roots)}


def reincluded_local(top, roots):
    """`!` lines outside .gitignore's Studio block that re-include machine-only paths (m0f-plan v4 NIT-2)."""
    text = _read(os.path.join(top, ".gitignore")) or ""
    try:
        rest, _block = ignore.split(text)
    except ignore.BlockError:
        return [".gitignore's Studio block markers are broken"]
    locals_ = [".claude/studio/local"] + ["%s/local" % r for r in roots]
    out = []
    for line in rest.splitlines():
        l = line.strip()
        if not l.startswith("!"):
            continue
        pat = l[1:].lstrip("/")
        if any(pat.rstrip("/") == x or pat.startswith(x + "/") for x in locals_):
            out.append(".gitignore re-includes machine-only Studio files outside Studio's block: %s" % l)
    return out
