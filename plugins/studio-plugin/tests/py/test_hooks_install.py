"""M0e: hooks.py install · status (m0e-plan v2 §3, §12.1). File formats only — no hook-manager binaries
(those run under --full: test_hooks_full.py). Real git in temporary repositories."""

import json
import os
import subprocess

from commit_base import CommitCase
from stdo.hooks import templates as T

HOOKS = os.path.join(".git", "hooks")


class Plain(CommitCase):
    install_hook = False

    def p(self, *rel):
        return os.path.join(self.repo, *rel)

    def test_fresh_install_is_idempotent_and_marked(self):
        out = self.hooks("install", "--json")
        self.assertEqual(out.returncode, 0, out.stderr)
        wrote = json.loads(out.stdout)["wrote"]
        self.assertEqual(len(wrote), 3)
        for f in (self.p(HOOKS, "pre-commit"), self.p(".git", "studio", "pre-commit")):
            self.assertIn(T.MARK, open(f).read())
            self.assertTrue(os.access(f, os.X_OK))
        self.assertIn("# >>> studio", open(self.p(".git", "info", "exclude")).read())
        mt = {f: os.stat(f).st_mtime_ns for f in wrote}
        out = self.hooks("install", "--json")
        self.assertEqual(json.loads(out.stdout)["wrote"], [])
        self.assertEqual(mt, {f: os.stat(f).st_mtime_ns for f in wrote})
        self.assertEqual(self.hooks("status").returncode, 0)

    def test_chain_keeps_the_previous_hook_first(self):
        trace = os.path.join(self.tmp, "prev-ran")
        self.exe(self.p(HOOKS, "pre-commit"), "#!/bin/sh\necho ran >> '%s'\nexit ${PREV_EXIT:-0}\n" % trace)
        self.assertEqual(self.hooks("install").returncode, 0)
        self.assertIn("ran", open(self.p(HOOKS, T.CHAINED)).read())
        self.write("src/a.ts")
        self.git("add", "src/a.ts")
        self.assertEqual(self.commit().returncode, 0)
        self.assertTrue(os.path.exists(trace))
        # the previous hook fails: its code stands and Studio's check does not run
        env = dict(self.env)
        env["PREV_EXIT"] = "3"
        self.write("studio/local/x")
        self.git("add", "-f", "studio/local/x")
        out = self.commit(env=env)
        self.assertNotEqual(out.returncode, 0)
        self.assertNotIn("Studio pre-commit", out.stderr)

    def test_non_executable_previous_hook_is_skipped_like_git(self):
        with open(self.p(HOOKS, "pre-commit"), "w") as f:
            f.write("#!/bin/sh\nexit 1\n")
        os.chmod(self.p(HOOKS, "pre-commit"), 0o644)
        self.assertEqual(self.hooks("install").returncode, 0)
        self.write("src/a.ts")
        self.git("add", "src/a.ts")
        self.assertEqual(self.commit().returncode, 0)

    def test_chained_name_conflict(self):
        self.exe(self.p(HOOKS, "pre-commit"), "#!/bin/sh\nexit 0\n")
        self.exe(self.p(HOOKS, T.CHAINED), "#!/bin/sh\necho other\n")
        out = self.hooks("install")
        self.assertEqual(out.returncode, 1)
        self.assertEqual(open(self.p(HOOKS, "pre-commit")).read(), "#!/bin/sh\nexit 0\n")

    def test_upgrade_replaces_only_the_shim(self):
        self.exe(self.p(HOOKS, "pre-commit"), "#!/bin/sh\n# prev\n")
        self.assertEqual(self.hooks("install").returncode, 0)
        with open(self.p(HOOKS, "pre-commit"), "w") as f:
            f.write("#!/bin/sh\n# studio:hook v0\n")
        self.assertNotEqual(self.hooks("status").returncode, 0)
        self.assertEqual(self.hooks("install").returncode, 0)
        self.assertEqual(open(self.p(HOOKS, "pre-commit")).read(), T.shim())
        self.assertEqual(open(self.p(HOOKS, T.CHAINED)).read(), "#!/bin/sh\n# prev\n")

    def test_runner_missing_message(self):
        self.exe(self.p(HOOKS, "pre-commit"), "#!/bin/sh\nexit 0\n")
        self.assertEqual(self.hooks("install").returncode, 0)
        os.remove(self.p(".git", "studio", "pre-commit"))
        self.write("src/a.ts")
        self.git("add", "src/a.ts")
        out = self.commit()
        self.assertNotEqual(out.returncode, 0)
        self.assertIn("rm \"", out.stderr)
        self.assertIn("mv \"", out.stderr)
        self.assertIn(T.CHAINED, out.stderr)

    def test_hooks_path_outside_or_tracked(self):
        outside = os.path.join(self.tmp, "global-hooks")
        os.makedirs(outside)
        self.git("config", "core.hooksPath", outside)
        out = self.hooks("install")
        self.assertEqual(out.returncode, 1)
        self.assertEqual(os.listdir(outside), [])
        self.git("config", "core.hooksPath", "githooks")
        os.makedirs(self.p("githooks"))
        out = self.hooks("install")
        self.assertEqual(out.returncode, 4)
        self.assertEqual(os.listdir(self.p("githooks")), [])
        self.assertNotEqual(self.hooks("status").returncode, 0)

    def test_overwriting_manager_detected(self):
        gen = "#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\nexit 0\n"
        self.exe(self.p(HOOKS, "pre-commit"), gen)
        out = self.hooks("install", "--json")
        self.assertEqual(out.returncode, 0)
        self.assertTrue(any("pre-commit manages git hooks" in w for w in json.loads(out.stdout)["warnings"]))
        self.assertEqual(self.hooks("status").returncode, 0)
        self.exe(self.p(HOOKS, "pre-commit"), gen)  # the manager reinstalls
        out = self.hooks("status")
        self.assertEqual(out.returncode, 1)
        self.assertIn("overwritten by pre-commit", out.stdout)

    def test_worktree_uses_the_shared_runner(self):
        self.assertEqual(self.hooks("install").returncode, 0)
        wt = os.path.join(self.tmp, "wt")
        self.git("worktree", "add", "-q", wt)
        self.write("studio/local/x", repo=wt)
        self.git("add", "-f", "studio/local/x", cwd=wt)
        out = self.commit(cwd=wt)
        self.assertNotEqual(out.returncode, 0)
        self.assertIn("machine-only", out.stderr)

    def test_exclude_keeps_other_lines_and_refuses_broken(self):
        ex = self.p(".git", "info", "exclude")
        with open(ex, "w") as f:
            f.write("*.mine\n")
        self.assertEqual(self.hooks("install").returncode, 0)
        text = open(ex).read()
        self.assertTrue(text.startswith("*.mine\n") and "/studio/local/" in text)
        with open(ex, "a") as f:
            f.write("# >>> studio (managed by /std init; edit with /std config) >>>\n")
        self.assertEqual(self.hooks("install").returncode, 1)

    def test_no_harness(self):
        bare = os.path.join(self.tmp, "bare")
        os.makedirs(bare)
        self.git("init", "-q", cwd=bare)
        self.assertEqual(self.hooks("install", cwd=bare).returncode, 2)


class Husky(CommitCase):
    install_hook = False

    def setUp(self):
        super().setUp()
        self.write("package.json", json.dumps({"devDependencies": {"husky": "^9"}}))
        hd = os.path.join(self.repo, ".husky", "_")
        os.makedirs(hd)
        # what husky 9 generates, in short: its hook runs the tracked script with sh -e
        self.exe(os.path.join(hd, "pre-commit"), '#!/bin/sh\nsh -e .husky/pre-commit\n')
        self.git("config", "core.hooksPath", ".husky/_")
        self.write(".husky/pre-commit", "npm test\n")
        self.git("add", "package.json", ".husky/pre-commit")
        self.git("commit", "-q", "--no-verify", "-m", "husky")

    def test_proposes_then_applies_once(self):
        out = self.hooks("install")
        self.assertEqual(out.returncode, 4)
        self.assertIn(T.BLOCK_BEGIN, out.stderr)
        self.assertEqual(self.read(".husky/pre-commit"), "npm test\n")
        self.assertEqual(sorted(os.listdir(os.path.join(self.repo, ".husky", "_"))), ["pre-commit"])
        self.assertNotEqual(self.hooks("status").returncode, 0)
        self.assertEqual(self.hooks("install", "--husky-apply").returncode, 0)
        self.assertEqual(self.hooks("install", "--husky-apply").returncode, 0)
        self.assertEqual(self.read(".husky/pre-commit").count(T.BLOCK_BEGIN), 1)
        self.assertEqual(self.hooks("status").returncode, 0)

    def test_block_runs_under_sh_e(self):
        self.write(".husky/pre-commit", "true\n")
        self.assertEqual(self.hooks("install", "--husky-apply").returncode, 0)
        self.write("studio/local/x")
        self.git("add", "-f", "studio/local/x")
        out = self.commit()
        self.assertNotEqual(out.returncode, 0)
        self.assertIn("machine-only", out.stderr)
        self.git("restore", "--staged", "studio/local/x")
        self.write("src/a.ts")
        self.git("add", "src/a.ts")
        self.assertEqual(self.commit().returncode, 0)
        # a clone without Studio's runner: the block does nothing (sh -e, last line)
        os.remove(os.path.join(self.repo, ".git", "studio", "pre-commit"))
        out = subprocess.run(["sh", "-e", ".husky/pre-commit"], cwd=self.repo, capture_output=True, text=True,
                             env=self.env)
        self.assertEqual(out.returncode, 0, out.stderr)

    def test_status_hook_ends_before_the_block(self):
        self.assertEqual(self.hooks("install", "--husky-apply").returncode, 0)
        self.write(".husky/pre-commit", "npm test\nexit 0\n" + T.husky_block())
        out = self.hooks("status")
        self.assertEqual(out.returncode, 1)
        self.assertIn("ends before the Studio block", out.stdout)

    def test_not_installed_in_this_clone(self):
        self.git("config", "--unset", "core.hooksPath")
        out = self.hooks("install", "--json")
        self.assertTrue(any("not installed" in w for w in json.loads(out.stdout)["warnings"]))


class Lefthook(CommitCase):
    install_hook = False

    def setUp(self):
        super().setUp()
        self.write("lefthook.yml", "pre-commit:\n  commands:\n    noop:\n      run: true\n")
        self.exe(os.path.join(self.repo, ".git", "hooks", "pre-commit"),
                 "#!/bin/sh\n# lefthook's hook (fake)\nexit 0\n")

    def test_local_file_and_exclude(self):
        self.assertEqual(self.hooks("install").returncode, 0)
        self.assertIn(T.lefthook_block(), self.read("lefthook-local.yml"))
        self.assertIn("/lefthook-local.yml", open(os.path.join(self.repo, ".git", "info", "exclude")).read())
        self.assertEqual(self.git("check-ignore", "-q", "lefthook-local.yml", check=False).returncode, 0)
        out = self.hooks("install", "--json")
        self.assertEqual(json.loads(out.stdout)["wrote"], [])
        self.assertEqual(self.hooks("status").returncode, 0)

    def test_existing_pre_commit_section_is_not_merged(self):
        self.write("lefthook-local.yml", "pre-commit:\n  commands:\n    mine:\n      run: echo\n")
        out = self.hooks("install")
        self.assertEqual(out.returncode, 1)
        self.assertEqual(self.read("lefthook-local.yml"), "pre-commit:\n  commands:\n    mine:\n      run: echo\n")
